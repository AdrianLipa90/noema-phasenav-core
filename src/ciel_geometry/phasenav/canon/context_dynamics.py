"""Canonical PhaseNav context field, attractors, vectors and orbits.

Context is not a label. It is a smooth potential field on the operational
torus T^36 generated by weighted PhaseNav states. Its local density lowers the
potential, while its local angular dispersion raises the viscosity. Semantic
motion is the damped orbit

    m d2(phi)/dt2 + mu_C(phi) d(phi)/dt = -grad U_C(phi).

The implementation is deterministic, gauge-periodic and stdlib-only.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
import hashlib
import json
import math
from typing import Iterable, Mapping, Sequence

from ..pnv_runtime import TAU
from .model import CanonicalConceptState, ETA_M_36D, KAPPA, PHASE_DIM

CONTEXT_BANDWIDTH = 4.0 * ETA_M_36D
_CONTEXT_EPS = 1.0e-300


def _rms(values: Sequence[float]) -> float:
    return math.sqrt(math.fsum(v * v for v in values) / len(values))


def _wrapped_delta(a: float, b: float) -> float:
    """Signed shortest displacement a-b in [-pi, pi)."""
    return (a - b + math.pi) % TAU - math.pi


@dataclass(frozen=True)
class PhaseVector36:
    """Gauge-locked position vector on T^36."""

    components: tuple[float, ...]

    def __post_init__(self) -> None:
        if len(self.components) != PHASE_DIM:
            raise ValueError(f"expected {PHASE_DIM} phase coordinates")
        if not all(math.isfinite(v) for v in self.components):
            raise ValueError("phase coordinates must be finite")
        object.__setattr__(
            self,
            "components",
            tuple(float(v) % TAU for v in self.components),
        )

    @classmethod
    def from_id(cls, eid: object) -> "PhaseVector36":
        return cls(CanonicalConceptState.from_id(eid).phase36)

    def angular_distance(self, other: "PhaseVector36") -> float:
        return _rms(
            tuple(
                _wrapped_delta(a, b)
                for a, b in zip(self.components, other.components)
            )
        )

    def chord_distance_squared(self, other: "PhaseVector36") -> float:
        return 2.0 * math.fsum(
            1.0 - math.cos(a - b)
            for a, b in zip(self.components, other.components)
        ) / PHASE_DIM

    def displaced(
        self,
        tangent: "TangentVector36",
        scale: float = 1.0,
    ) -> "PhaseVector36":
        return PhaseVector36(
            tuple(
                phase + scale * velocity
                for phase, velocity in zip(
                    self.components,
                    tangent.components,
                )
            )
        )


@dataclass(frozen=True)
class TangentVector36:
    """Tangent, force or velocity vector in T_phi(T^36)."""

    components: tuple[float, ...]

    def __post_init__(self) -> None:
        if len(self.components) != PHASE_DIM:
            raise ValueError(f"expected {PHASE_DIM} tangent coordinates")
        if not all(math.isfinite(v) for v in self.components):
            raise ValueError("tangent coordinates must be finite")
        object.__setattr__(
            self,
            "components",
            tuple(float(v) for v in self.components),
        )

    @classmethod
    def zero(cls) -> "TangentVector36":
        return cls((0.0,) * PHASE_DIM)

    @property
    def norm(self) -> float:
        return _rms(self.components)

    def scaled(self, factor: float) -> "TangentVector36":
        return TangentVector36(tuple(factor * v for v in self.components))

    def plus(self, other: "TangentVector36") -> "TangentVector36":
        return TangentVector36(
            tuple(a + b for a, b in zip(self.components, other.components))
        )


@dataclass(frozen=True)
class ContextAnchor:
    """Weighted source of the contextual potential."""

    anchor_id: str
    vector: PhaseVector36
    weight: float
    semantic_mass: float

    def __post_init__(self) -> None:
        if not self.anchor_id:
            raise ValueError("anchor_id must not be empty")
        if not math.isfinite(self.weight) or self.weight <= 0.0:
            raise ValueError("anchor weight must be positive")
        if not math.isfinite(self.semantic_mass) or self.semantic_mass <= 0.0:
            raise ValueError("semantic mass must be positive")

    @classmethod
    def from_id(
        cls,
        eid: object,
        *,
        weight: float | None = None,
    ) -> "ContextAnchor":
        state = CanonicalConceptState.from_id(eid)
        return cls(
            anchor_id=str(eid),
            vector=PhaseVector36(state.phase36),
            weight=state.semantic_mass if weight is None else float(weight),
            semantic_mass=state.semantic_mass,
        )


@dataclass(frozen=True)
class FieldSample:
    """Local canonical context observables at one T^36 position."""

    position: PhaseVector36
    density: float
    potential: float
    viscosity: float
    local_variance: float
    gradient: TangentVector36
    force: TangentVector36

    @property
    def gradient_norm(self) -> float:
        return self.gradient.norm


@dataclass(frozen=True)
class ContextPotential:
    """Smooth density potential generated by PhaseNav context anchors.

    d_c^2(phi,a) = (2/D) sum_i [1-cos(phi_i-a_i)]
    K_a(phi)     = exp[-d_c^2/(2 h^2)]
    rho_C(phi)   = sum_a w_a K_a / sum_a w_a
    U_C(phi)     = -kappa ln rho_C(phi)
    sigma_C^2    = sum_a w_a K_a d_c^2 / sum_a w_a K_a
    mu_C(phi)    = kappa [1 + rho_C(1 + sigma_C^2/h^2)]
    """

    anchors: tuple[ContextAnchor, ...]
    bandwidth: float = CONTEXT_BANDWIDTH

    def __post_init__(self) -> None:
        if not self.anchors:
            raise ValueError("context requires at least one anchor")
        if not math.isfinite(self.bandwidth) or self.bandwidth <= 0.0:
            raise ValueError("bandwidth must be positive")
        ordered = tuple(sorted(self.anchors, key=lambda anchor: anchor.anchor_id))
        ids = [anchor.anchor_id for anchor in ordered]
        if len(ids) != len(set(ids)):
            raise ValueError("context anchor IDs must be unique")
        object.__setattr__(self, "anchors", ordered)

    @classmethod
    def from_concepts(
        cls,
        concepts: Iterable[object],
        *,
        weights: Mapping[str, float] | None = None,
        bandwidth: float = CONTEXT_BANDWIDTH,
    ) -> "ContextPotential":
        anchors = []
        for concept in concepts:
            key = str(concept)
            explicit = None if weights is None else weights.get(key)
            anchors.append(ContextAnchor.from_id(concept, weight=explicit))
        return cls(tuple(anchors), bandwidth=float(bandwidth))

    @property
    def digest_sha256(self) -> str:
        payload = {
            "bandwidth": self.bandwidth,
            "anchors": [
                {
                    "id": anchor.anchor_id,
                    "weight": anchor.weight,
                    "semantic_mass": anchor.semantic_mass,
                    "vector": anchor.vector.components,
                }
                for anchor in self.anchors
            ],
        }
        raw = json.dumps(
            payload,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
        return hashlib.sha256(raw).hexdigest()

    def context_vector(self) -> PhaseVector36:
        """Weighted circular resultant of all context anchors."""
        out = []
        for dimension in range(PHASE_DIM):
            x = math.fsum(
                anchor.weight
                * math.cos(anchor.vector.components[dimension])
                for anchor in self.anchors
            )
            y = math.fsum(
                anchor.weight
                * math.sin(anchor.vector.components[dimension])
                for anchor in self.anchors
            )
            out.append(math.atan2(y, x) % TAU if x or y else 0.0)
        return PhaseVector36(tuple(out))

    def sample(
        self,
        position: PhaseVector36 | Sequence[float],
    ) -> FieldSample:
        p = (
            position
            if isinstance(position, PhaseVector36)
            else PhaseVector36(tuple(position))
        )
        weight_sum = math.fsum(anchor.weight for anchor in self.anchors)
        kernels: list[float] = []
        distances_sq: list[float] = []
        for anchor in self.anchors:
            distance_sq = p.chord_distance_squared(anchor.vector)
            kernel = anchor.weight * math.exp(
                -distance_sq
                / (2.0 * self.bandwidth * self.bandwidth)
            )
            distances_sq.append(distance_sq)
            kernels.append(kernel)

        local_weight = max(math.fsum(kernels), _CONTEXT_EPS)
        density = min(
            1.0,
            max(_CONTEXT_EPS, local_weight / weight_sum),
        )
        potential = -KAPPA * math.log(density)
        local_variance = math.fsum(
            kernel * distance_sq
            for kernel, distance_sq in zip(kernels, distances_sq)
        ) / local_weight
        viscosity = KAPPA * (
            1.0
            + density
            * (
                1.0
                + local_variance
                / (self.bandwidth * self.bandwidth)
            )
        )

        gradient_components = []
        prefactor = (
            KAPPA
            / (self.bandwidth * self.bandwidth * PHASE_DIM)
        )
        for dimension in range(PHASE_DIM):
            numerator = math.fsum(
                kernel
                * math.sin(
                    p.components[dimension]
                    - anchor.vector.components[dimension]
                )
                for kernel, anchor in zip(kernels, self.anchors)
            )
            gradient_components.append(
                prefactor * numerator / local_weight
            )
        gradient = TangentVector36(tuple(gradient_components))
        force = gradient.scaled(-1.0)
        return FieldSample(
            position=p,
            density=density,
            potential=potential,
            viscosity=viscosity,
            local_variance=local_variance,
            gradient=gradient,
            force=force,
        )


@dataclass(frozen=True)
class Attractor:
    """A converged density mode and fixed-point candidate of the context field."""

    attractor_id: str
    vector: PhaseVector36
    support_ids: tuple[str, ...]
    density: float
    potential: float
    viscosity: float
    gradient_norm: float
    strength: float

    def to_dict(self) -> dict:
        data = asdict(self)
        data["vector"] = list(self.vector.components)
        return data


def _mean_shift_mode(
    context: ContextPotential,
    start: PhaseVector36,
    *,
    tolerance: float,
    max_iterations: int,
) -> PhaseVector36:
    current = start
    for _ in range(max_iterations):
        kernels = []
        for anchor in context.anchors:
            distance_sq = current.chord_distance_squared(anchor.vector)
            kernels.append(
                anchor.weight
                * math.exp(
                    -distance_sq
                    / (2.0 * context.bandwidth * context.bandwidth)
                )
            )
        new_components = []
        for dimension in range(PHASE_DIM):
            x = math.fsum(
                kernel
                * math.cos(anchor.vector.components[dimension])
                for kernel, anchor in zip(kernels, context.anchors)
            )
            y = math.fsum(
                kernel
                * math.sin(anchor.vector.components[dimension])
                for kernel, anchor in zip(kernels, context.anchors)
            )
            if x == 0.0 and y == 0.0:
                new_components.append(current.components[dimension])
            else:
                new_components.append(math.atan2(y, x) % TAU)
        updated = PhaseVector36(tuple(new_components))
        if current.angular_distance(updated) <= tolerance:
            return updated
        current = updated
    return current


def find_attractors(
    context: ContextPotential,
    *,
    tolerance: float = 1.0e-10,
    max_iterations: int = 256,
    merge_radius: float = ETA_M_36D / 4.0,
) -> tuple[Attractor, ...]:
    """Find context modes by circular mean shift and deterministic clustering."""
    if (
        tolerance <= 0.0
        or max_iterations < 1
        or merge_radius <= 0.0
    ):
        raise ValueError("invalid attractor search parameters")

    clusters: list[dict] = []
    for anchor in context.anchors:
        mode = _mean_shift_mode(
            context,
            anchor.vector,
            tolerance=tolerance,
            max_iterations=max_iterations,
        )
        matched = None
        for cluster in clusters:
            if (
                mode.angular_distance(cluster["vector"])
                <= merge_radius
            ):
                matched = cluster
                break
        if matched is None:
            clusters.append(
                {
                    "vector": mode,
                    "support": [anchor.anchor_id],
                }
            )
        else:
            matched["support"].append(anchor.anchor_id)

    attractors = []
    ordered = sorted(
        clusters,
        key=lambda cluster: (
            context.sample(cluster["vector"]).potential,
            tuple(
                round(value, 12)
                for value in cluster["vector"].components
            ),
        ),
    )
    for index, cluster in enumerate(ordered):
        sample = context.sample(cluster["vector"])
        attractors.append(
            Attractor(
                attractor_id=f"A{index:03d}",
                vector=cluster["vector"],
                support_ids=tuple(sorted(cluster["support"])),
                density=sample.density,
                potential=sample.potential,
                viscosity=sample.viscosity,
                gradient_norm=sample.gradient_norm,
                strength=sample.density / sample.viscosity,
            )
        )
    return tuple(attractors)


@dataclass(frozen=True)
class OrbitStep:
    step: int
    time: float
    position: PhaseVector36
    velocity: TangentVector36
    density: float
    potential: float
    viscosity: float
    gradient_norm: float
    kinetic_energy: float
    total_energy: float

    def to_dict(self) -> dict:
        return {
            "step": self.step,
            "time": self.time,
            "position": list(self.position.components),
            "velocity": list(self.velocity.components),
            "density": self.density,
            "potential": self.potential,
            "viscosity": self.viscosity,
            "gradient_norm": self.gradient_norm,
            "kinetic_energy": self.kinetic_energy,
            "total_energy": self.total_energy,
        }


@dataclass(frozen=True)
class OrbitTrace:
    context_digest_sha256: str
    semantic_mass: float
    steps: tuple[OrbitStep, ...]
    converged: bool
    terminal_attractor: str | None

    def to_dict(self) -> dict:
        return {
            "context_digest_sha256": self.context_digest_sha256,
            "semantic_mass": self.semantic_mass,
            "converged": self.converged,
            "terminal_attractor": self.terminal_attractor,
            "steps": [step.to_dict() for step in self.steps],
        }


def trace_orbit(
    context: ContextPotential,
    initial: PhaseVector36 | Sequence[float] | object,
    *,
    semantic_mass: float | None = None,
    initial_velocity: TangentVector36 | Sequence[float] | None = None,
    dt: float = 0.5,
    max_steps: int = 1024,
    tolerance: float = 1.0e-7,
    attractors: Sequence[Attractor] | None = None,
) -> OrbitTrace:
    """Integrate the canonical damped context orbit by semi-implicit Euler."""
    if isinstance(initial, PhaseVector36):
        position = initial
        inferred_mass = None
    elif (
        isinstance(initial, Sequence)
        and not isinstance(initial, (str, bytes))
    ):
        position = PhaseVector36(tuple(float(v) for v in initial))
        inferred_mass = None
    else:
        state = CanonicalConceptState.from_id(initial)
        position = PhaseVector36(state.phase36)
        inferred_mass = state.semantic_mass

    mass = inferred_mass if semantic_mass is None else float(semantic_mass)
    if mass is None:
        raise ValueError("semantic_mass is required for a raw vector")
    if not math.isfinite(mass) or mass <= 0.0:
        raise ValueError("semantic_mass must be positive")
    if (
        not math.isfinite(dt)
        or dt <= 0.0
        or max_steps < 1
        or tolerance <= 0.0
    ):
        raise ValueError("invalid orbit integration parameters")

    if initial_velocity is None:
        velocity = TangentVector36.zero()
    elif isinstance(initial_velocity, TangentVector36):
        velocity = initial_velocity
    else:
        velocity = TangentVector36(
            tuple(float(v) for v in initial_velocity)
        )

    attractor_list = tuple(
        find_attractors(context)
        if attractors is None
        else attractors
    )
    history: list[OrbitStep] = []
    converged = False
    for step_index in range(max_steps + 1):
        sample = context.sample(position)
        kinetic = (
            0.5
            * mass
            * math.fsum(v * v for v in velocity.components)
            / PHASE_DIM
        )
        history.append(
            OrbitStep(
                step=step_index,
                time=step_index * dt,
                position=position,
                velocity=velocity,
                density=sample.density,
                potential=sample.potential,
                viscosity=sample.viscosity,
                gradient_norm=sample.gradient_norm,
                kinetic_energy=kinetic,
                total_energy=sample.potential + kinetic,
            )
        )
        if (
            sample.gradient_norm <= tolerance
            and velocity.norm <= tolerance
        ):
            converged = True
            break
        acceleration = TangentVector36(
            tuple(
                (force - sample.viscosity * speed) / mass
                for force, speed in zip(
                    sample.force.components,
                    velocity.components,
                )
            )
        )
        velocity = velocity.plus(acceleration.scaled(dt))
        position = position.displaced(velocity, dt)

    terminal = None
    if attractor_list:
        final_position = history[-1].position
        nearest = min(
            attractor_list,
            key=lambda attractor: final_position.angular_distance(
                attractor.vector
            ),
        )
        if (
            final_position.angular_distance(nearest.vector)
            <= ETA_M_36D
        ):
            terminal = nearest.attractor_id
    return OrbitTrace(
        context_digest_sha256=context.digest_sha256,
        semantic_mass=mass,
        steps=tuple(history),
        converged=converged,
        terminal_attractor=terminal,
    )
