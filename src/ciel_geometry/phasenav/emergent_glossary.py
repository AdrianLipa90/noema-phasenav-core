"""Emergent 36D glossary paths for canonical PhaseNav cards.

Edges generated by this module are geometric hypotheses.  They are always
marked ``chyba`` and ``canon_allowed=False`` until an external review or source
artifact explicitly promotes them.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
import hashlib
import heapq
import json
import math
from typing import Any, Iterable, Mapping, Sequence

import numpy as np

from .canonical_cards import CanonicalCard, SECTORS, TAU, VECTOR_DIM

try:  # SciPy is an existing PhaseNav dependency, but keep a small-data fallback.
    from scipy.spatial import cKDTree
except ImportError:  # pragma: no cover - exercised only in reduced installations
    cKDTree = None

PATH_MARKER_SCHEMA = "PHASENAV-36D-PATH/1"
EDGE_SCHEMA = "PHASENAV-EMERGENT-EDGE/1"
ETA_M_36D = 36.0 * (math.log(2.0) / (24.0 * math.pi))

SECTOR_WEIGHTS = np.asarray(
    [2.0] * 6 + [2.0] * 6 + [1.5] + [1.0] * 23,
    dtype=np.float64,
)
SECTOR_WEIGHT_SUM = float(SECTOR_WEIGHTS.sum())


def _digest(value: Any, length: int = 24) -> str:
    raw = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
    ).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:length]


def wrapped_delta(source: Sequence[float], target: Sequence[float]) -> np.ndarray:
    src = np.asarray(source, dtype=np.float64)
    dst = np.asarray(target, dtype=np.float64)
    if src.shape != (VECTOR_DIM,) or dst.shape != (VECTOR_DIM,):
        raise ValueError("source and target must be 36D")
    return ((dst - src + math.pi) % TAU) - math.pi


def weighted_torus_distance(source: Sequence[float], target: Sequence[float]) -> float:
    delta = np.abs(wrapped_delta(source, target))
    return float(np.sum(delta * SECTOR_WEIGHTS) / SECTOR_WEIGHT_SUM)


def sector_distances(delta: Sequence[float]) -> dict[str, float]:
    arr = np.abs(np.asarray(delta, dtype=np.float64))
    return {
        name: float(np.mean(arr[slc]))
        for name, slc in SECTORS.items()
    }


def _transition_lane(distances: Mapping[str, float]) -> str:
    dominant = max(distances, key=distances.get)
    return {
        "lorentz": "frequency",
        "intention": "phase",
        "soul": "identity",
        "semantic": "semantic",
    }[dominant]


def _berry_connection(source: Sequence[float], target: Sequence[float]) -> float:
    src = np.exp(1j * np.asarray(source, dtype=np.float64)) / math.sqrt(VECTOR_DIM)
    dst = np.exp(1j * np.asarray(target, dtype=np.float64)) / math.sqrt(VECTOR_DIM)
    return float(np.angle(np.vdot(src, dst)))


@dataclass(frozen=True)
class Phase36PathMarker:
    source_fingerprint: str
    target_fingerprint: str
    delta_36d: tuple[float, ...]
    sector_distance: dict[str, float]
    weighted_distance: float
    berry_connection_rad: float
    coherence: float
    winding_signature: tuple[int, ...]
    fingerprint: str
    schema: str = PATH_MARKER_SCHEMA
    dimension: int = VECTOR_DIM

    @classmethod
    def between(cls, source: CanonicalCard, target: CanonicalCard) -> "Phase36PathMarker":
        delta = wrapped_delta(source.marker_36d.vector, target.marker_36d.vector)
        distances = sector_distances(delta)
        weighted = weighted_torus_distance(
            source.marker_36d.vector,
            target.marker_36d.vector,
        )
        coherence = float((1.0 + np.mean(np.cos(delta))) / 2.0)
        winding = tuple(
            int(round((t - s - d) / TAU))
            for s, t, d in zip(
                source.marker_36d.vector,
                target.marker_36d.vector,
                delta,
            )
        )
        payload = {
            "schema": PATH_MARKER_SCHEMA,
            "source": source.marker_36d.fingerprint,
            "target": target.marker_36d.fingerprint,
            "delta": [round(float(x), 12) for x in delta],
        }
        return cls(
            source_fingerprint=source.marker_36d.fingerprint,
            target_fingerprint=target.marker_36d.fingerprint,
            delta_36d=tuple(float(x) for x in delta),
            sector_distance={k: round(v, 12) for k, v in distances.items()},
            weighted_distance=round(weighted, 12),
            berry_connection_rad=round(
                _berry_connection(source.marker_36d.vector, target.marker_36d.vector),
                12,
            ),
            coherence=round(coherence, 12),
            winding_signature=winding,
            fingerprint="p36path:" + _digest(payload, 32),
        )

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class EmergentEdge:
    source_card_id: str
    target_card_id: str
    marker_36d: Phase36PathMarker
    operator_hook: str = "emergent"
    operator_card_id: str = "op_emergent_36d"
    transition_lane: str = "semantic"
    holonomic_viscosity: float = 0.0
    phasenav_affordance: float = 0.0
    path_integral: float = 0.0
    epistemic_status: str = "chyba"
    confidence: float = 0.0
    canon_allowed: bool = False
    provenance: dict[str, Any] = field(default_factory=dict)
    schema: str = EDGE_SCHEMA

    @classmethod
    def between(
        cls,
        source: CanonicalCard,
        target: CanonicalCard,
        *,
        rank: int,
        generator: str = "phase36-knn",
    ) -> "EmergentEdge":
        marker = Phase36PathMarker.between(source, target)
        distance = marker.weighted_distance
        affordance = math.exp(-distance / max(ETA_M_36D, 1e-12))
        viscosity = distance / (distance + ETA_M_36D)
        path_integral = viscosity * distance / max(affordance, 1e-12)
        confidence = marker.coherence * affordance
        lane = _transition_lane(marker.sector_distance)
        return cls(
            source_card_id=source.card_id,
            target_card_id=target.card_id,
            marker_36d=marker,
            transition_lane=lane,
            holonomic_viscosity=round(viscosity, 12),
            phasenav_affordance=round(affordance, 12),
            path_integral=round(path_integral, 12),
            confidence=round(confidence, 12),
            provenance={
                "generator": generator,
                "rank": rank,
                "source_binding": "INFERENCE",
                "canon_rule": "manual-review-required",
            },
        )

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        marker = data.pop("marker_36d")
        data["phase36_path_marker"] = marker
        # Compatibility fields used by the old loader/solver.
        data["src"] = self.source_card_id
        data["dst"] = self.target_card_id
        data["concept_id"] = self.source_card_id
        return data


@dataclass(frozen=True)
class GlossaryPath:
    card_sequence: tuple[str, ...]
    edges: tuple[EmergentEdge, ...]
    total_path_integral: float
    berry_holonomy_rad: float
    epistemic_status: str = "chyba"
    canon_allowed: bool = False
    marker_schema: str = PATH_MARKER_SCHEMA

    def to_dict(self) -> dict[str, Any]:
        return {
            "card_sequence": list(self.card_sequence),
            "edges": [edge.to_dict() for edge in self.edges],
            "total_path_integral": self.total_path_integral,
            "berry_holonomy_rad": self.berry_holonomy_rad,
            "epistemic_status": self.epistemic_status,
            "canon_allowed": self.canon_allowed,
            "marker_schema": self.marker_schema,
        }


class EmergentGlossary:
    """A directed k-nearest-neighbour glossary over canonical 36D cards."""

    def __init__(self, cards: Iterable[CanonicalCard], edges: Iterable[EmergentEdge] = ()) -> None:
        self.cards = {card.card_id: card for card in cards}
        self.edges: list[EmergentEdge] = list(edges)
        self._adjacency: dict[str, list[EmergentEdge]] = {}
        self._reindex()

    def _reindex(self) -> None:
        self._adjacency.clear()
        for edge in self.edges:
            self._adjacency.setdefault(edge.source_card_id, []).append(edge)
        for bucket in self._adjacency.values():
            bucket.sort(key=lambda edge: (edge.path_integral, edge.target_card_id))

    def build(
        self,
        *,
        neighbours: int = 6,
        max_distance: float | None = None,
        symmetric: bool = True,
    ) -> list[EmergentEdge]:
        if neighbours < 1:
            raise ValueError("neighbours must be >= 1")
        ordered = sorted(self.cards.values(), key=lambda card: card.card_id)
        if len(ordered) < 2:
            self.edges = []
            self._reindex()
            return []

        phases = np.asarray([card.marker_36d.vector for card in ordered], dtype=np.float64)
        features = np.concatenate((np.cos(phases), np.sin(phases)), axis=1)
        k = min(neighbours + 1, len(ordered))

        if cKDTree is not None:
            tree = cKDTree(features)
            _, indices = tree.query(features, k=k)
            neighbour_rows = np.atleast_2d(indices)
        else:  # pragma: no cover - only for environments without SciPy
            if len(ordered) > 4096:
                raise RuntimeError("SciPy is required to build a large emergent glossary")
            diffs = features[:, None, :] - features[None, :, :]
            euclidean = np.linalg.norm(diffs, axis=2)
            neighbour_rows = np.argsort(euclidean, axis=1)[:, :k]

        selected: dict[tuple[str, str], EmergentEdge] = {}
        for i, raw_row in enumerate(neighbour_rows):
            candidates: list[tuple[float, int]] = []
            for j_raw in np.atleast_1d(raw_row):
                j = int(j_raw)
                if i == j:
                    continue
                distance = weighted_torus_distance(phases[i], phases[j])
                if max_distance is not None and distance > max_distance:
                    continue
                candidates.append((distance, j))
            candidates.sort(key=lambda item: (item[0], ordered[item[1]].card_id))
            for rank, (_, j) in enumerate(candidates[:neighbours], start=1):
                edge = EmergentEdge.between(ordered[i], ordered[j], rank=rank)
                selected[(edge.source_card_id, edge.target_card_id)] = edge
                if symmetric:
                    reverse = EmergentEdge.between(ordered[j], ordered[i], rank=rank)
                    selected[(reverse.source_card_id, reverse.target_card_id)] = reverse

        self.edges = sorted(
            selected.values(),
            key=lambda edge: (edge.source_card_id, edge.path_integral, edge.target_card_id),
        )
        self._reindex()
        return self.edges

    def edge_between(self, source_card_id: str, target_card_id: str) -> EmergentEdge | None:
        for edge in self._adjacency.get(source_card_id, []):
            if edge.target_card_id == target_card_id:
                return edge
        return None

    def neighbours(self, card_id: str, limit: int | None = None) -> list[EmergentEdge]:
        edges = list(self._adjacency.get(card_id, []))
        return edges if limit is None else edges[:limit]

    def trace(self, source_card_id: str, target_card_id: str) -> GlossaryPath | None:
        if source_card_id not in self.cards or target_card_id not in self.cards:
            return None
        if source_card_id == target_card_id:
            return GlossaryPath((source_card_id,), (), 0.0, 0.0)

        queue: list[tuple[float, str]] = [(0.0, source_card_id)]
        costs: dict[str, float] = {source_card_id: 0.0}
        previous: dict[str, tuple[str, EmergentEdge]] = {}

        while queue:
            cost, node = heapq.heappop(queue)
            if cost > costs.get(node, math.inf):
                continue
            if node == target_card_id:
                break
            for edge in self._adjacency.get(node, []):
                next_cost = cost + edge.path_integral
                if next_cost < costs.get(edge.target_card_id, math.inf):
                    costs[edge.target_card_id] = next_cost
                    previous[edge.target_card_id] = (node, edge)
                    heapq.heappush(queue, (next_cost, edge.target_card_id))

        if target_card_id not in previous:
            return None

        reverse_edges: list[EmergentEdge] = []
        cursor = target_card_id
        while cursor != source_card_id:
            prior, edge = previous[cursor]
            reverse_edges.append(edge)
            cursor = prior
        path_edges = tuple(reversed(reverse_edges))
        sequence = [source_card_id] + [edge.target_card_id for edge in path_edges]
        berry = float(sum(edge.marker_36d.berry_connection_rad for edge in path_edges) % TAU)
        return GlossaryPath(
            card_sequence=tuple(sequence),
            edges=path_edges,
            total_path_integral=round(sum(edge.path_integral for edge in path_edges), 12),
            berry_holonomy_rad=round(berry, 12),
        )

    def edges_to_jsonl(self) -> str:
        return "\n".join(
            json.dumps(edge.to_dict(), ensure_ascii=False, sort_keys=True)
            for edge in self.edges
        ) + "\n"


