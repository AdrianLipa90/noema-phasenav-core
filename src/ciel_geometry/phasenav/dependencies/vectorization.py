"""Vectorization operators derived from normalized geometry.

The operator layer consumes geometric states.  It does not invent semantic
coordinates from opaque string hashes.  Signed vector components are tangent
coordinates generated by shortest oriented displacements on the phase crystal.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

from .crystal import PhaseCrystal
from .geometry import IdentityAxis, OrientedScalar


@dataclass(frozen=True)
class GeometricVector:
    components: tuple[float, ...]
    source: str

    @property
    def dimension(self) -> int:
        return len(self.components)


@dataclass(frozen=True)
class VectorizationOperator:
    """Convert geometric relations into tangent vectors."""

    name: str = "phase-crystal-log-map"

    def tangent(self, source: PhaseCrystal, target: PhaseCrystal) -> GeometricVector:
        return GeometricVector(source.tangent_to(target), self.name)

    def centered_scalars(
        self,
        values: Iterable[float],
        *,
        axis: IdentityAxis = IdentityAxis(),
    ) -> GeometricVector:
        components = tuple(OrientedScalar.from_axis(v, axis).value for v in values)
        return GeometricVector(components, "identity-axis-log-map")


def lift_turn_vector(components: Iterable[float], closure_period: float) -> GeometricVector:
    """Represent normalized-turn tangent components in a chosen angular unit."""
    period = float(closure_period)
    if period <= 0.0:
        raise ValueError("closure_period must be positive")
    return GeometricVector(tuple(float(x) * period for x in components), "phase-closure-lift")
