"""Minimal PhaseNav observer-to-CIELingo generation-plan example."""
from __future__ import annotations

import json

from ciel_geometry.phasenav import (
    DynamicsConfig,
    HTRIConfig,
    HTRIOscillatorField,
    M_sentence_phase,
    ObserverState,
    ObserverToGenerationPipeline,
    PhaseVector36,
)


observer = ObserverState(
    observer_id="USER007",
    phase=PhaseVector36(tuple(M_sentence_phase("initial observer state"))),
)

pipeline = ObserverToGenerationPipeline(
    htri=HTRIOscillatorField(
        HTRIConfig(
            oscillators=120,
            base_frequency_hz=7.83,
            backend="auto",
        )
    ),
    dynamics=DynamicsConfig(steps=48),
)

result = pipeline.run(
    observer,
    "A relation is observed and must become a coherent generative state.",
    intention_text="preserve meaning, provenance and relational context",
    ai_induction="AI inference proposal",
    mcp_inductions=("memory MCP state", "tool MCP state"),
)

# PhaseNav ends here. CIELingo consumes this payload and performs language
# projection. No text is generated by this PhaseNav example.
print(json.dumps(result.plan.to_cielingo_payload(), ensure_ascii=False, indent=2))
